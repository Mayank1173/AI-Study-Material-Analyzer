class TestSemanticGroupingUsesSharedEmbeddings:
    """Paraphrases must merge via the knowledge base's own embedder."""

    def _analyzer(self):
        import tempfile
        from pathlib import Path

        from rag.embeddings import get_embedder
        from rag.knowledge_base import KnowledgeBase
        from rag.vectorstore.sqlite_store import SqliteVectorStore
        from app.services.pyq_service import PyqAnalyzer

        store = SqliteVectorStore(Path(tempfile.mkdtemp()) / "v.db")
        kb = KnowledgeBase(get_embedder("deterministic"), store)
        return PyqAnalyzer(knowledge_base=kb), kb

    def test_paraphrases_are_merged(self) -> None:
        analyzer, _ = self._analyzer()
        pairs = analyzer.find_similar_questions(
            [
                "Explain TCP and UDP. (10 marks)",
                "Explain the TCP and UDP protocols. (10 marks)",
            ],
            threshold=0.6,
        )
        assert pairs, "paraphrases should be reported as similar"
        i, j, score = pairs[0]
        assert (i, j) == (0, 1)
        assert score >= 0.6

    def test_unrelated_questions_are_not_merged(self) -> None:
        analyzer, _ = self._analyzer()
        pairs = analyzer.find_similar_questions(
            [
                "Explain TCP and UDP. (10 marks)",
                "Describe the water cycle. (5 marks)",
            ],
            threshold=0.99,
        )
        assert pairs == []

    def test_knowledge_base_exposes_embed(self) -> None:
        _, kb = self._analyzer()
        vectors = kb.embed(["hello world", "another phrase"])
        assert len(vectors) == 2
        assert all(len(v) > 0 for v in vectors)

    def test_ranking_prefers_frequency_then_marks(self) -> None:
        from app.services.pyq_service import PyqAnalyzer

        ranked = PyqAnalyzer(knowledge_base=None).rank_questions(
            [
                {"question": "rare big", "frequency": 1, "marks": 20, "importance": "Medium"},
                {"question": "common small", "frequency": 3, "marks": 5, "importance": "High"},
            ],
            5,
        )
        # Frequency dominates: the question seen 3 times outranks a 20-mark one.
        assert ranked[0]["question"] == "common small"

    def test_respects_top_n(self) -> None:
        from app.services.pyq_service import PyqAnalyzer

        ranked = PyqAnalyzer(knowledge_base=None).rank_questions(
            [{"question": f"q{i}", "frequency": i, "marks": 2} for i in range(1, 6)],
            2,
        )
        assert len(ranked) == 2


