TestingSession = sessionmaker(
    bind=test_engine, autoflush=False, autocommit=False, expire_on_commit=False
)


def _reset() -> None:
    Base.metadata.drop_all(bind=test_engine)
    Base.metadata.create_all(bind=test_engine)


def _make_user(name: str, email: str) -> User:
    db = TestingSession()
    user = User(name=name, email=email, password_hash=hash_password(TEST_PASSWORD))
    db.add(user)
    db.commit()
    db.refresh(user)
    db.close()
    return user


def _create_course(client, headers, name="Biology", code="BIO101") -> dict:
    response = client.post(
        "/api/courses", json={"name": name, "code": code}, headers=headers
    )
    assert response.status_code == 201
    return response.json()


def _upload_and_process(client, headers, course_id, *, title="Biology Notes", content) -> dict:
    response = client.post(
        "/api/materials/upload",
        data={"course_id": course_id, "title": title, "material_type": "notes"},
        files={"file": ("notes.txt", BytesIO(content.encode()), "text/plain")},
        headers=headers,
    )
    assert response.status_code == 201
    material = response.json()
    process = client.post(
        f"/api/materials/{material['id']}/process", headers=headers
    )
    assert process.status_code == 200
    assert process.json()["status"] == "processed"
    return material


