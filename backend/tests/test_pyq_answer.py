class TestAnalyzeReporting:
    """/api/pyqs/analyze must let the frontend tell failure modes apart."""

    def test_requires_auth(self, client) -> None:
        c, _ = client
        resp = c.post("/api/pyqs/analyze", json={"num_questions": 5})
        assert resp.status_code in (401, 403)

    def test_reports_analyzed_and_failed_files(self, client) -> None:
        c, _ = client
        user = _make_user("Alice", "alice@example.com")
        headers = {"Authorization": f"Bearer {create_access_token(user.id)}"}
        course = _create_course(c, headers)

        good = _upload_pyq(
            c,
            headers,
            course["id"],
            title="2024 Paper",
            name="paper2024.txt",
            content=(
                "1. Explain TCP and UDP.\n"
                "2. Explain CSMA/CD in detail.\n"
                "3. Differentiate OSI and TCP/IP models.\n"
            ),
        )
        # A file that does not exist on disk is reported as a failure.
        missing = _upload_pyq(
            c,
            headers,
            course["id"],
            title="Missing Paper",
            name="paper2025.txt",
            content="1. Explain queuing networks.",
        )
        db = TestingSession()
        row = db.get(StudyMaterial, uuid.UUID(missing["id"]))
        row.stored_file_name = "does-not-exist.txt"
        db.commit()
        db.close()

        resp = c.post(
            "/api/pyqs/analyze",
            json={
                "course_id": course["id"],
                "num_questions": 10,
                "file_ids": [good["id"], missing["id"]],
            },
            headers=headers,
        )
        assert resp.status_code == 200
        data = resp.json()
        assert data["analyzed_files"] == ["paper2024.txt"]
        assert len(data["failed_files"]) == 1
        assert data["summary"]["papers_failed"] == 1
        assert data["summary"]["papers_analyzed"] == 1
        # Real questions are returned; none are fabricated.
        assert data["total_questions"] >= 1
        assert all(q["question"] for q in data["questions"])

