class TestPyqMetadataNeverGroundsAnswers:
    """PYQ frequency/repetition/ranking data must not leak into answer context.

    The spec separates the two roles: question papers drive analysis only, and
    only study materials may ground an answer.
    """

    def test_answer_prompt_has_no_field_for_pyq_statistics(self) -> None:
        import inspect

        from rag.pyq_answer import answer_pyq_question

        params = set(inspect.signature(answer_pyq_question).parameters)
        # The service must not even accept PYQ statistics as input.
        assert not params & {
            "frequency",
            "years",
            "years_appeared",
            "importance",
            "repetition",
            "pyq_data",
            "rank",
        }

    def test_pyq_prompt_never_repeats_analysis_statistics(self, client) -> None:
        c, mock_llm = client
        user = _make_user("Alice", "alice@example.com")
        headers = {"Authorization": f"Bearer {create_access_token(user.id)}"}
        course = _create_course(c, headers)
        _upload_and_process(
            c,
            headers,
            course["id"],
            content=(
                "TCP provides connection-oriented reliable delivery with "
                "sequence numbers and acknowledgements. UDP is connectionless "
                "and offers no delivery or ordering guarantees."
            ),
        )

        resp = c.post(
            "/api/pyqs/answer",
            json={
                "question": "Explain TCP and UDP.",
                "course_id": course["id"],
                "marks": 10,
                "answer_format": "Medium",
            },
            headers=headers,
        )
        assert resp.status_code == 200
        assert resp.json()["has_context"] is True

        prompt = mock_llm.last_prompt.lower()
        # Study-material content is present...
        assert "sequence numbers" in prompt
        # ...but no analysis statistic is used as grounding context.
        assert "frequency" not in prompt
        assert "years appeared" not in prompt
        assert "importance" not in prompt
        assert "repeated" not in prompt


class TestPyqMaterialsAreNotGroundingSources:
    """Question papers feed analysis only and must stay out of the RAG index."""

    def test_type_classification(self) -> None:
        from app.services.study_material_service import (
            is_pyq_material_type,
            is_rag_grounding_material,
        )

        for value in ("pyq", "PYQ", "Question Paper", "question_bank", "pyq_paper"):
            assert is_pyq_material_type(value) is True
            assert is_rag_grounding_material(value) is False

        for value in ("notes", "ppt", "pdf", "module_notes", None, ""):
            assert is_pyq_material_type(value) is False
            assert is_rag_grounding_material(value) is True

    def test_pyq_upload_is_processed_but_not_retrievable(self, client) -> None:
        c, _ = client
        user = _make_user("Alice", "alice@example.com")
        headers = {"Authorization": f"Bearer {create_access_token(user.id)}"}
        course = _create_course(c, headers)

        upload = c.post(
            "/api/materials/upload",
            data={
                "course_id": course["id"],
                "title": "2024 Question Paper",
                "material_type": "pyq",
            },
            files={
                "file": (
                    "pyq2024.txt",
                    BytesIO(
                        b"1. Explain TCP and UDP. "
                        b"2. Explain CSMA/CD in detail. "
                        b"3. Differentiate OSI and TCP IP models."
                    ),
                    "text/plain",
                )
            },
            headers=headers,
        )
        assert upload.status_code == 201
        material = upload.json()

        process = c.post(f"/api/materials/{material['id']}/process", headers=headers)
        assert process.status_code == 200
        assert process.json()["status"] == "processed"

        # The paper is readable (processed), yet it must not ground an answer.
        resp = c.post(
            "/api/pyqs/answer",
            json={"question": "Explain TCP and UDP.", "course_id": course["id"]},
            headers=headers,
        )
        assert resp.status_code == 200
        data = resp.json()
        assert data["has_context"] is False
        assert data["sources"] == []
        assert data["answer"].strip() != ""

    def test_same_content_as_study_material_is_retrievable(self, client) -> None:
        """Control case: proves the PYQ exclusion is what causes the miss.

        Without this, the previous test could pass simply because retrieval was
        broken for this content in general.
        """
        c, _ = client
        user = _make_user("Alice", "alice@example.com")
        headers = {"Authorization": f"Bearer {create_access_token(user.id)}"}
        course = _create_course(c, headers)

        _upload_and_process(
            c,
            headers,
            course["id"],
            title="Networking Notes",
            content=(
                "TCP provides connection-oriented reliable delivery with "
                "sequence numbers and acknowledgements."
            ),
        )

        resp = c.post(
            "/api/pyqs/answer",
            json={"question": "Explain TCP and UDP.", "course_id": course["id"]},
            headers=headers,
        )
        assert resp.status_code == 200
        data = resp.json()
        assert data["has_context"] is True
        assert len(data["sources"]) >= 1
        assert all(s["material_title"] == "Networking Notes" for s in data["sources"])