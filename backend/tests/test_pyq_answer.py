def _upload_pyq(client, headers, course_id, *, title, content, name="pyq.txt") -> dict:
    """Upload a question paper the same way the PYQ page does."""
    response = client.post(
        "/api/materials/upload",
        data={"course_id": course_id, "title": title, "material_type": "pyq"},
        files={"file": (name, BytesIO(content.encode()), "text/plain")},
        headers=headers,
    )
    assert response.status_code == 201
